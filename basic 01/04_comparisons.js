// Comparisons in JavaScript
console.log(3 == '3'); // true (loose equality)
console.log(3 === '3'); // false (strict equality)
console.log(3 != '3'); // false (loose inequality)
console.log(3 !== '3'); // true (strict inequality)
console.log(5 > 3); // true
console.log(3 < 5); // true
console.log(5 >= 5);
console.log(4 <= 3);
console.log('apple' > 'banana'); // false (lexicographical comparison)
console.log('2' > '12'); // true (lexicographical comparison)
console.log(true == 1); // true
console.log(false == 0);
console.log(true === 1); // false
console.log(null == undefined); // true
console.log(null === undefined); // false
console.log(null > 0); // false
console.log(null >= 0); // true
console.log(undefined > 0); 